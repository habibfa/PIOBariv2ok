const keywordRegex = /\b(TABLET|CAPSULE|INJECTION|SOLUTION|SYRUP|SUSPENSION|DROPS|CREAM|OINTMENT|GEL|POWDER|INFUSION|SUPPOSITORY|AEROSOL|INHALATION|VACCINE|FLEXPEN|SHAMPOO|LIQUID|ENEMA|SPRAY)\b/i;
const keywordRegexAlt = /\b(OPHT|TAB|CAP|AMP|TB RO)\b/i;

const groups = {};

rawData.split('\n').forEach(line => {
  const t = line.trim();
  if (!t) return;
  
  // Custom grouping logic for edge cases
  let baseName = "";
  let formStr = "";
  
  let match = t.match(keywordRegex);
  if (!match) {
    match = t.match(keywordRegexAlt);
  }
  
  if (match) {
    baseName = t.substring(0, match.index).trim();
    formStr = t.substring(match.index).trim();
    if (baseName.endsWith(",")) baseName = baseName.slice(0, -1).trim();
  } else {
    // split by numbers (dosage) if no keyword
    const numMatch = t.match(/\b\d+/);
    if (numMatch) {
      baseName = t.substring(0, numMatch.index).trim();
      formStr = t.substring(numMatch.index).trim();
    } else {
      baseName = t;
      formStr = "Sediaan Lainnya";
    }
  }
  
  if (baseName === "") baseName = t; // fallback
  
  // Normalize baseName
  let norm = baseName.toUpperCase()
    .replace(/\s+/g, ' ')
    .replace(/\(.*\)/g, '')
    .trim();
    
  if (norm === 'CENDO') {
    // keep full word for cendo
    norm = baseName.toUpperCase();
  }
  if (norm.startsWith('VAKSIN')) {
    norm = baseName.toUpperCase();
  }
  if (norm.startsWith('VITAMIN')) {
    norm = baseName.toUpperCase();
  }
  
  // Special consolidations
  if (norm.includes('CEFAT')) norm = 'CEFAT';
  if (norm.includes('CENDO MYDRIATIL')) norm = 'CENDO MYDRIATIL';
  if (norm.includes('CENDO TROPIN')) norm = 'CENDO TROPIN';
  if (norm.includes('CHLORAMPHENICOL')) norm = 'CHLORAMPHENICOL';
  if (norm.includes('CITICHOLIN') || norm.includes('CITICOLINE')) norm = 'CITICOLINE';
  if (norm.includes('COTRIMOXAZOLE')) norm = 'COTRIMOXAZOLE';
  if (norm.includes('DIAZEPAM')) norm = 'DIAZEPAM';
  if (norm.includes('DEXTROSE')) norm = 'DEXTROSE';
  if (norm.includes('LAXADINE')) norm = 'LAXADINE';
  if (norm.includes('LANSOPRAZOLE')) norm = 'LANSOPRAZOLE';
  if (norm.includes('LEVOFLOXACIN')) norm = 'LEVOFLOXACIN';
  if (norm.includes('METHYLPREDNISOLONE')) norm = 'METHYLPREDNISOLONE';
  if (norm.includes('MIDAZOLAM')) norm = 'MIDAZOLAM';
  if (norm.includes('ONDANSETRON')) norm = 'ONDANSETRON';
  if (norm.includes('OFLOXACIN')) norm = 'OFLOXACIN';
  if (norm.includes('OSELTAMIVIR')) norm = 'OSELTAMIVIR';
  if (norm.includes('PARACETAMOL')) norm = 'PARACETAMOL';
  if (norm.includes('SANMOL')) norm = 'SANMOL';
  if (norm.includes('SPORETIK')) norm = 'SPORETIK';
  if (norm.includes('VOMETA')) norm = 'VOMETA';
  if (norm.includes('ZAMEL')) norm = 'ZAMEL';
  if (norm.includes('ZINC')) norm = 'ZINC (ZINKID/ZINCPRO)';
  
  if (!groups[norm]) {
    groups[norm] = {
      baseName: norm,
      forms: []
    };
  }
  if (formStr) groups[norm].forms.push(formStr.replace(/perbaiki master!/i, '').trim());
});

const outputDrugs = [];
